import { test, expect, type Page } from '@playwright/test'
async function tab(page: Page, title: string) { await page.getByRole('navigation', { name: 'Object tabs' }).getByRole('link', { name: title, exact: true }).click() }
async function create(page: Page, source = 'mock-deployment-order-2') {
  await page.getByRole('navigation', { name: 'Prototype navigation' }).getByRole('link', { name: 'Потребности в коммуникациях', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Потребности в коммуникациях', exact: true })).toBeVisible()
  await page.getByRole('region', { name: 'Потребности в коммуникациях', exact: true }).getByRole('link', { name: 'need-001 · запись проводки', exact: true }).click()
  await page.getByLabel('Источник', { exact: true }).selectOption(source)
  await page.getByRole('button', { name: 'Создать MOCK заявку' }).click()
  await expect(page.getByRole('status', { name: 'Статус заявки' })).toHaveText(/PENDING/)
}
async function decision(page: Page, outcome: 'ALLOWED' | 'DENIED') {
  await expect(page.getByRole('button', { name: outcome, exact: true })).toHaveCount(0)
  await page.getByLabel('MOCK режим принятия решения').check()
  await page.getByRole('button', { name: outcome, exact: true }).click()
  await expect(page.getByRole('status', { name: 'Статус заявки' })).toHaveText(new RegExp(outcome))
  await expect(page.getByLabel('MOCK режим принятия решения')).toHaveCount(0)
}
test('complete business to policy journey, immutable provenance, reuse and denial', async ({ page }) => {
  const apiCalls: string[] = []
  page.on('request', r => { if (/\/api\//.test(r.url())) apiCalls.push(r.url()) })
  await page.goto('/prototype/processes')
  await page.getByRole('link', { name: 'Settlement', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Settlement', exact: true })).toBeVisible()
  await tab(page, 'Потребности')
  await page.getByRole('link', { name: 'need-001 · запись проводки', exact: true }).click()
  await tab(page, 'Профиль')
  await page.getByRole('link', { name: 'Order-to-Ledger HTTPS', exact: true }).click()
  await tab(page, 'Коммуникации')
  await page.getByRole('link', { name: 'OrderClient → LedgerApi', exact: true }).click()
  await tab(page, 'Ревизии')
  await page.getByRole('link', { name: 'OrderClient → LedgerApi / rev-1', exact: true }).click()
  await expect(page.getByLabel('Основные свойства')).toContainText('TCP / destination 443–443')
  await tab(page, 'Участники')
  await page.getByRole('link', { name: 'dep-ledger-1', exact: true }).click()
  await tab(page, 'Ресурс')
  await page.getByRole('link', { name: 'ledger-api-01', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'ledger-api-01', exact: true })).toBeVisible()
  await create(page)
  await expect(page.getByLabel('Основные свойства')).toContainText('mock-deployment-order-2')
  await expect(page.getByLabel('Основные свойства')).toContainText('mock-deployment-ledger')
  await expect(page.getByLabel('Основные свойства')).toContainText('mock-revision')
  await expect(page.getByLabel('Основные свойства')).toContainText('mock-need')
  await page.getByRole('navigation', { name: 'Prototype navigation' }).getByRole('link', { name: 'Заявки на доступ', exact: true }).click()
  await page.getByRole('button', { name: 'Следующая страница', exact: true }).click()
  await page.getByRole('link', { name: 'Simulation Q1', exact: true }).click()
  await decision(page, 'ALLOWED')
  await page.getByRole('link', { name: 'Открыть PolicyRule' }).click()
  const ruleUrl = page.url()
  await tab(page, 'Основания разрешения')
  await expect(page.getByText(/origin mock-simulation-request-1/)).toBeVisible()
  await page.getByRole('link', { name: 'Simulation Q1', exact: true }).click()
  await tab(page, 'Бизнес-основание')
  await page.getByRole('link', { name: 'Settlement', exact: true }).click()
  await expect(page.getByRole('navigation', { name: 'Breadcrumbs' })).toContainText('Бизнес-процессы')
  await create(page)
  await decision(page, 'ALLOWED')
  await page.getByRole('link', { name: 'Открыть PolicyRule' }).click()
  expect(page.url()).toBe(ruleUrl)
  await tab(page, 'Основания разрешения')
  await expect(page.getByRole('link', { name: 'Simulation Q1', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Simulation Q2', exact: true })).toBeVisible()
  await expect(page.getByText(/origin mock-simulation-request-1/)).toBeVisible()
  await create(page)
  await decision(page, 'DENIED')
  await expect(page.getByRole('link', { name: 'Открыть PolicyRule' })).toHaveCount(0)
  await expect(page.getByLabel('Основные свойства')).toContainText('null')
  await page.getByRole('navigation', { name: 'Prototype navigation' }).getByRole('link', { name: 'Правила политики', exact: true }).click()
  await expect(page.getByRole('link', { name: /^Simulation P/ })).toHaveCount(1)
  await page.getByRole('link', { name: 'Simulation P1', exact: true }).click()
  await tab(page, 'Основания разрешения')
  await expect(page.getByRole('link', { name: 'Simulation Q3', exact: true })).toHaveCount(0)
  expect(apiCalls).toEqual([])
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Объект не найден' })).toBeVisible()
})
test('invalid roles rejected, denial first creates no rule, static rule reused', async ({ page }) => {
  await page.goto('/prototype/needs/mock-need')
  await page.getByLabel('Источник', { exact: true }).selectOption('mock-deployment-ledger')
  await page.getByRole('button', { name: 'Создать MOCK заявку' }).click()
  await expect(page.getByRole('alert')).toContainText('не соответствуют')
  await create(page)
  await decision(page, 'DENIED')
  await page.getByRole('navigation', { name: 'Prototype navigation' }).getByRole('link', { name: 'Правила политики', exact: true }).click()
  await expect(page.getByRole('link', { name: /^Simulation P/ })).toHaveCount(0)
  await create(page, 'mock-deployment-order')
  await decision(page, 'ALLOWED')
  await page.getByRole('link', { name: 'Открыть PolicyRule' }).click()
  await expect(page).toHaveURL(/\/policy\/mock-rule$/)
  await tab(page, 'Основания разрешения')
  await expect(page.getByRole('link', { name: 'Q1 · разрешённая заявка', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Simulation Q2', exact: true })).toBeVisible()
})
