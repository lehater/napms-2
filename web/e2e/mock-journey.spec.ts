test('transition boundary rejects invalid, repeated and competing decisions without changing provenance', () => {
  expect(() => submit(emptySimulation, newSubject, 'mock-need', 'C')).toThrow('нет совместимого')
  expect(() => submit(emptySimulation, { ...newSubject, interactionRevisionId: 'mock-application' }, 'mock-need')).toThrow('не соответствуют')
  const [pending, q3] = submit(emptySimulation, newSubject, 'mock-need')
  const allowed = decide(pending, q3, 'ALLOWED')
  const snapshot = JSON.stringify(allowed)
  for (const outcome of ['ALLOWED', 'DENIED'] as const) expect(() => decide(allowed, q3, outcome)).toThrow('Повторное или конкурентное')
  expect(JSON.stringify(allowed)).toBe(snapshot)
  expect(pending.requests[0].state).toBe('PENDING')
  expect(allowed.rules[0].fields.subject).toBe(subjectKey(newSubject))
  const [repeat, q4] = submit(allowed, newSubject, 'mock-need')
  const reused = decide(repeat, q4, 'ALLOWED')
  expect(reused.rules).toEqual(allowed.rules)
  expect(reused.requests[1].fields.policyRuleId).toBe(allowed.rules[0].id)
  const [third, q5] = submit(reused, newSubject, 'mock-need')
  const denied = decide(third, q5, 'DENIED')
  expect(denied.rules).toEqual(allowed.rules)
  expect(denied.requests[2].fields.policyRuleId).toBe('null')
  const [historical, id] = submit(emptySimulation, originalSubject, 'mock-need')
  const p1 = decide(historical, id, 'ALLOWED')
  expect(p1.rules).toHaveLength(0)
  expect(p1.requests[0].fields.policyRuleId).toBe('mock-rule')
  const inactive = { ...allowed, rules: allowed.rules.map(rule => rule.kind === 'PolicyRule' ? { ...rule, state: 'Inactive' as const } : rule) }
  expect(inactive.rules[0].state).toBe('Inactive')
  const [repeatedInactive, id2] = submit(inactive, newSubject, 'mock-need')
  expect(decide(repeatedInactive, id2, 'ALLOWED').rules).toEqual(inactive.rules)
})

