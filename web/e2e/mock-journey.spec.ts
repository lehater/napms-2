import { test, expect, type Page } from '@playwright/test'
import { decide, submit, emptySimulation, newSubject, originalSubject, subjectKey } from '../src/prototype/simulation'
async function tab(page: Page, title: string) { await page.getByRole('navigation', { name: 'Object tabs' }).getByRole('link', { name: title, exact: true }).click() }
async function create(page: Page, destination = 'mock-deployment-ledger-2') {
  await page.getByLabel('Демонстрационная роль').selectOption('Requester')
  await page.getByRole('navigation', { name: 'Prototype navigation' }).getByRole('link', { name: 'Потребности в коммуникациях', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Потребности в коммуникациях', exact: true })).toBeVisible()
  await page.getByRole('region', { name: 'Потребности в коммуникациях', exact: true }).getByRole('link', { name: 'need-001 · запись проводки', exact: true }).click()
  await tab(page, 'Коммуникация')
  await page.getByLabel('Получатель', { exact: true }).selectOption(destination)
  await page.getByRole('button', { name: 'Подтвердить и отправить заявку →' }).click()
  await expect(page.getByRole('status', { name: 'Статус заявки' })).toHaveText(/PENDING/)
}
async function decision(page: Page, outcome: 'ALLOWED' | 'DENIED') {
  await expect(page.getByRole('button', { name: outcome, exact: true })).toHaveCount(0)
  await page.getByLabel('MOCK режим принятия решения').check()
  await expect(page.getByRole('radio', { checked: true })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Подтвердить решение', exact: true })).toBeDisabled()
  await page.getByRole('radio', { name: outcome, exact: true }).check()
  await expect(page.getByRole('status', { name: 'Статус заявки' })).toHaveText(/PENDING/)
  await page.getByRole('dialog', { name: 'Подтверждение ' + outcome }).getByRole('button', { name: 'Подтвердить ' + outcome, exact: true }).click()
  await expect(page.getByRole('status', { name: 'Статус заявки' })).toHaveText(new RegExp(outcome))
  await expect(page.getByLabel('MOCK режим принятия решения')).toHaveCount(0)
}
